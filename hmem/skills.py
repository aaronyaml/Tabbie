"""Skill proposals: validation + install (only after the user approves).

Skills are the strongest write path (their descriptions load into every Claude session), so:
- SKILL.md only: no scripts, hooks or allowed-tools.
- Installed as ~/.claude/skills/hermes-gen-<name>/, never over an existing skill name.
- Every shell command inside a code block must start with an allowlisted program.
- Skills derived from external-trust evidence are rejected.
"""

from __future__ import annotations

import os
import re
import shutil
import time
from pathlib import Path

from . import doc as D
from . import security

PREFIX = "hermes-gen-"
MAX_MD = 8000
ALLOWED_CMDS = {"npm", "npx", "node", "python", "python3", "uv", "pytest", "git", "rg", "grep", "find", "ls", "cat",
                "ffmpeg", "ffprobe", "jq", "make", "cargo", "go", "swift", "xcodebuild", "pnpm", "yarn", "bun", "tsc",
                "eslint", "prettier", "deno", "sed", "awk", "head", "tail", "wc", "mkdir", "cp", "mv", "echo", "cd"}
_BAD_TRIGGERS = re.compile(r"(?i)\b(any|every|all) (request|task|message|prompt)s?\b|\balways use\b")


def skills_dir() -> Path:
    return Path(os.environ.get("HMEM_SKILLS_DIR", Path.home() / ".claude" / "skills")).expanduser()


def _commands(md: str) -> list[str]:
    cmds = []
    for block in re.findall(r"```(?:bash|sh|shell|zsh)?\n(.*?)```", md, re.S):
        for ln in block.splitlines():
            ln = ln.strip().lstrip("$ ").strip()
            if ln and not ln.startswith("#"):
                cmds.append(ln)
    return cmds


def validate(name: str, md: str, trust: str, project: str | None = None) -> list[str]:
    errs = []
    if trust == "external":
        errs.append("skill derived from external content")
    if not D.valid_slug(name) or name.startswith(PREFIX):
        errs.append("skill name must be a plain slug (the hermes-gen- prefix is added on install)")
    if project:
        from . import projects
        if (projects._pdir(project) / "skills" / name).exists():
            errs.append(f"project skill {name} already exists")
    elif (skills_dir() / name).exists() or (skills_dir() / f"{PREFIX}{name}").exists():
        errs.append(f"a skill named {name} already exists")
    if len(md) > MAX_MD:
        errs.append("SKILL.md too long")
    meta, body = D.parse(md)
    if not meta.get("name") or not meta.get("description"):
        errs.append("SKILL.md needs name + description frontmatter")
    if meta.get("allowed-tools") or meta.get("hooks"):
        errs.append("generated skills may not declare allowed-tools or hooks")
    if _BAD_TRIGGERS.search(str(meta.get("description") or "")):
        errs.append("description must name a specific situation, not 'any request'")
    if len(str(meta.get("description") or "")) > 400:
        errs.append("description too long")
    for c in _commands(md):
        prog = c.split()[0].split("/")[-1]
        if prog not in ALLOWED_CMDS or re.search(r"\|\s*(ba|z)?sh\b|\beval\b|\bcurl\b|\bwget\b|>\s*~?/?\.", c):
            errs.append(f"command not allowed in a generated skill: {c[:80]}")
    findings = security.scan(md)
    if security.blocked(findings):
        errs.append("poisoning scan: " + "; ".join(f["rule"] for f in findings if f["severity"] == "block"))
    return errs


def install(name: str, md: str, proposal_id: str, project: str | None = None) -> str:
    """Global skills go to ~/.claude/skills/hermes-gen-<name>; a Project's skills stay inside that
    project's memory (memory/projects/<id>/skills/<name>/SKILL.md) and are offered only to its workers."""
    errs = validate(name, md, "agent", project=project)
    if errs:
        raise ValueError("; ".join(errs))
    meta, body = D.parse(md)
    if project:
        from . import projects, store
        dest = projects._pdir(project) / "skills" / name
        if dest.exists():
            raise ValueError(f"project skill {name} already exists")
        meta["name"] = name
        store._atomic_write(dest / "SKILL.md", D.render(meta, body + f"\n\n<!-- generated by the Hermes dreamer, "
                                                                     f"proposal {proposal_id} -->\n"))
        store.commit([f"projects/{project}/skills/{name}"], f"proposal:{proposal_id}", f"install project skill {name}")
        return str(dest)
    meta["name"] = f"{PREFIX}{name}"
    dest = skills_dir() / f"{PREFIX}{name}"
    dest.mkdir(parents=True, exist_ok=False)
    (dest / "SKILL.md").write_text(D.render(meta, body + f"\n\n<!-- generated by the Hermes dreamer, proposal "
                                                         f"{proposal_id}, installed {time.strftime('%Y-%m-%d')} -->\n"))
    return str(dest)


def uninstall(name: str) -> str:
    """Generated skills only. Moved to ~/hermes/backups, never deleted."""
    if not name.startswith(PREFIX):
        raise ValueError("only hermes-gen- skills can be removed this way")
    src = skills_dir() / name
    dest = Path.home() / "hermes" / "backups" / f"skill-{name}-{int(time.time())}"
    shutil.move(str(src), str(dest))
    return str(dest)
